            builder.AppendLine(AutoGeneratedMarker);
            builder.AppendLine(GeneratedFileOwnershipMarker);
            builder.AppendLine();
        }

        private static string ResolveProjectNamespace(string projectFile)
        {
            try
            {
                var content = ReadProjectFile(projectFile);
                var match = Regex.Match(content, @"<RootNamespace>([^<]+)</RootNamespace>");
                if (match.Success)
                {
                    return match.Groups[1].Value.Trim().Replace('-', '_');
                }
            }
            catch
            {
            }

            return Path.GetFileNameWithoutExtension(projectFile).Replace('-', '_');
        }

