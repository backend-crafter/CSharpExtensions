            sb.AppendLine("    {");
            sb.AppendLine("        var pascalKey = char.ToUpper(sourceKey[0]) + sourceKey.Substring(1);");
            sb.AppendLine("        if (element.TryGetProperty(sourceKey, out var prop) || element.TryGetProperty(pascalKey, out prop))");
            sb.AppendLine("        {");
            sb.AppendLine("            if (prop.ValueKind == JsonValueKind.Null)");
