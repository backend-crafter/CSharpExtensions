            foreach (var prop in currentMandatoryFields)
            {
                sb.AppendLine($"            if (!doc.RootElement.TryGetProperty({CSharpStringLiteral(prop.CamelName)}, out _) && !doc.RootElement.TryGetProperty({CSharpStringLiteral(prop.Name)}, out _)) return false;");
            }
            
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");
            sb.AppendLine("        catch");
            sb.AppendLine("        {");
            sb.AppendLine("            return false;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
