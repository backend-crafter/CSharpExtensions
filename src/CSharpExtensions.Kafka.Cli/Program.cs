            sb.AppendLine("    private static void WriteDateTimeOffsetProperty(Utf8JsonWriter writer, JsonElement element, string targetKey, string sourceKey)");
            sb.AppendLine("    {");
            sb.AppendLine("        var pascalKey = char.ToUpper(sourceKey[0]) + sourceKey.Substring(1);");
