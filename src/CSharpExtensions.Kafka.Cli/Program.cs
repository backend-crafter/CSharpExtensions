            sb.AppendLine("        {");
            sb.AppendLine("            return null;");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine();

            // 3. Generate Upcaster step implementations
            for (int i = 0; i < historicalSchemas.Count; i++)
            {
                var sourceVer = i + 1;
                var targetVer = i + 2;
                var sourceVerName = $"{baseModelName}V{sourceVer}";
                var isLatest = targetVer > historicalSchemas.Count;
                var targetVerName = isLatest ? currentModelName : $"{baseModelName}V{targetVer}";
                var targetVerShortName = isLatest ? "Latest" : $"V{targetVer}";

