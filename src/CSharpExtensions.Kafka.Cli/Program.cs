                sb.AppendLine();
                sb.AppendLine("        using var doc = JsonDocument.Parse(rawPayloadJson);");
                sb.AppendLine("        var root = doc.RootElement;");
                sb.AppendLine();
                sb.AppendLine("        var bufferWriter = new ArrayBufferWriter<byte>(rawPayloadJson.Length + 256);");
                sb.AppendLine("        using (var writer = new Utf8JsonWriter(bufferWriter, new JsonWriterOptions { Indented = false }))");
                sb.AppendLine("        {");
                sb.AppendLine("            writer.WriteStartObject();");
                sb.AppendLine();

                // Map fields to target schema
                var targetProps = (targetVer <= historicalSchemas.Count) 
                    ? historicalSchemas[targetVer - 1].Fields.Select(kv => new PropertyMetadata(char.ToUpper(kv.Key[0]) + kv.Key.Substring(1), kv.Value)).ToList()
                    : currentProperties;

                var sourceKeys = historicalSchemas[i].Fields.Keys.ToHashSet();

                foreach (var prop in targetProps)
                {
                    // Check if name matches directly (ignoring case and underscores)
                    var matchedKey = sourceKeys.FirstOrDefault(k => string.Equals(k.Replace("_", ""), prop.CamelName.Replace("_", ""), StringComparison.OrdinalIgnoreCase));
                    if (matchedKey != null)
                    {
                        var writeMethod = GetWriteMethodName(prop.Type);
                        sb.AppendLine($"            {writeMethod}(writer, root, {CSharpStringLiteral(prop.CamelName)}, {CSharpStringLiteral(matchedKey)});");
                    }
                    else
                    {
                        // Missing property - supply default
                        var defaultWriteCall = GetDefaultWriteCall(prop.CamelName, prop.Type);
                        sb.AppendLine($"            {defaultWriteCall}");
                    }
                }

                sb.AppendLine("            writer.WriteEndObject();");
                sb.AppendLine("        }");
                sb.AppendLine();
                sb.AppendLine("        return Encoding.UTF8.GetString(bufferWriter.WrittenSpan);");
                sb.AppendLine("    }");
                sb.AppendLine();

                // Generate high-performance writing helpers inside each class to make it self-contained
                GenerateWriterHelpers(sb);

                sb.AppendLine("}");
                sb.AppendLine();
            }

            return sb.ToString();
        }

        private static string GetWriteMethodName(string type)
        {
            bool isNullable = type.EndsWith("?") || type.Contains("Nullable<");
            var cleanType = type.Replace("?", "").Replace("Nullable<", "").Replace(">", "").Trim();

            switch (cleanType)
            {
                case "string":
                    return "WriteStringProperty";
                case "Guid":
                    return isNullable ? "WriteNullableGuidProperty" : "WriteGuidProperty";
                case "long":
                    return isNullable ? "WriteNullableLongProperty" : "WriteLongProperty";
                case "int":
                    return isNullable ? "WriteNullableIntProperty" : "WriteIntProperty";
                case "decimal":
                    return isNullable ? "WriteNullableDecimalProperty" : "WriteDecimalProperty";
                case "bool":
                    return isNullable ? "WriteNullableBoolProperty" : "WriteBoolProperty";
                case "DateTimeOffset":
                    return isNullable ? "WriteNullableDateTimeOffsetProperty" : "WriteDateTimeOffsetProperty";
                default:
                    return "WriteStringProperty";
            }
        }

        private static string GetDefaultWriteCall(string targetKey, string type)
        {
            bool isNullable = type.EndsWith("?") || type.Contains("Nullable<");
            var targetLiteral = CSharpStringLiteral(targetKey);
            if (isNullable)
            {
                return $"writer.WriteNull({targetLiteral});";
            }

            var cleanType = type.Replace("?", "").Replace("Nullable<", "").Replace(">", "").Trim();
            switch (cleanType)
            {
                case "string":
                    return $"writer.WriteNull({targetLiteral});";
                case "Guid":
                    return $"writer.WriteString({targetLiteral}, Guid.Empty);";
                case "long":
                case "int":
                    return $"writer.WriteNumber({targetLiteral}, 0);";
                case "decimal":
                    return $"writer.WriteNumber({targetLiteral}, 0.0m);";
                case "bool":
                    return $"writer.WriteBoolean({targetLiteral}, false);";
                case "DateTimeOffset":
                    return $"writer.WriteString({targetLiteral}, DateTimeOffset.MinValue);";
                default:
                    return $"writer.WriteNull({targetLiteral});";
            }
        }

